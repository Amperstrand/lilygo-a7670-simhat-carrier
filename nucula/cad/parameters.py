def derived() -> dict:
    """Quantities computed from the parameters above (single source)."""
    d = {}
    # interior cavity (board-local u,v ranges kept free for the board)
    d["int_u0"] = -WALL_T  # wall inner faces sit outside the board plane
    d["board_u0"], d["board_u1"] = 0.0, Measured.board_w
    # lid interior floor height above enclosure floor (z)
    tall_main = max(
        comp_height("J2"), comp_height("J1"), comp_height("U3"), comp_height("U8")
    )
    d["lid_int_z"] = PCB_SUPPORT_H + Measured.board_t + tall_main + COMP_Z_CLEARANCE
    # screen deck: glass must clear the USB shell (tallest thing it covers)
    d["deck_floor_z"] = PCB_SUPPORT_H + Measured.board_t + comp_height("J1") + 0.40
    d["deck_top_z"] = d["deck_floor_z"] + SCREEN_GLASS_T + SCREEN_RECESS_CLEAR + SCREEN_POP_T + 0.60
    # J2 wire apex clearance blister height (housing top + wire bend)
    d["j2_blister_z"] = PCB_SUPPORT_H + Measured.board_t + comp_height("J2") + BATTERY_WIRE_D + 0.70
    # keyboard blister interior height (header height if ever fitted)
    d["kb_blister_z"] = PCB_SUPPORT_H + Measured.board_t + KB_HEADER_H + 0.80
    # battery pocket
    d["pocket_z_top"] = PCB_SUPPORT_H - PCB_Z_CLEARANCE          # battery top limit
    d["pocket_z_bot"] = d["pocket_z_top"] - BATTERY_T - BATTERY_CLEARANCE_Z
    d["case_z_min"] = d["pocket_z_bot"] - BATTERY_POCKET_FLOOR   # battery bump face
    # battery pocket XY (u 7..55.6 keeps clear of corner zones; v 45.8..71.9)
    d["pocket_u"] = (7.0, 55.6)
    d["pocket_v"] = (45.8, 71.9)
    d["battery_u"] = (21.6, 21.6 + BATTERY_L)
    d["battery_v"] = (47.5, 47.5 + BATTERY_W)
    # USB wall opening (board-local v range, z range in enclosure coords)
    bz0 = PCB_SUPPORT_H + Measured.board_t - 1.60   # plug boot low edge
    bz1 = PCB_SUPPORT_H + Measured.board_t + comp_height("J1") / 2 + USB_PLUG_H / 2
    usb_c = (USB_BODY_V[0] + USB_BODY_V[1]) / 2.0
    half = USB_PLUG_W / 2.0 + USB_OPENING_CLEAR
    d["usb_open_v"] = (usb_c - half, usb_c + half)
    d["usb_open_z"] = (bz0 - USB_OPENING_CLEAR, bz1 + USB_OPENING_CLEAR)
    d["usb_mating_u"] = -0.80    # derived_kicad: J1 shell face overhangs edge
    d["end_wall_inner_v"] = Measured.MAIN_V_END + END_REMNANT_ALLOW + REMNANT_GAP
    # battery service slot in the left wall (aligns with J2 housing)
    d["bat_slot_v"] = (46.3, 54.2)
    d["bat_slot_z"] = (PCB_SUPPORT_H + 0.2, PCB_SUPPORT_H + Measured.board_t + comp_height("J2") + 0.4)
    return d


D = derived()
