"""All Nucula enclosure parameters in one place.

Measured board values are LOADED from analysis/*.json (generated by
scripts/extract_kicad_geometry.py from the KiCad board file). Only
*design decisions* live here as literals.

Provenance classes (mirrors docs/geometry_provenance.md):
  extracted_kicad             parsed from nucula-v2.kicad_pcb / footprint libs
  derived_kicad               computed from extracted geometry
  manufacturer_doc            from a Nucula repo document or component drawing
  conservative_assumption     documented guess; must be measured (see
                              MEASUREMENTS_NEEDED.md)
  enclosure_design_decision   our choice; a changeable parameter

Coordinate system (board-local, millimetres):
  Origin = main-board outline corner at KiCad (50, 50).
  u = KiCad X - 50  (0..60 across the board width)
  v = KiCad Y - 50  (0..73 main section; 75..110 keyboard section)
  z = 0 at the enclosure floor top surface; the PCB bottom face sits at
      z = PCB_SUPPORT_H.  KiCad axes are preserved (v grows toward the
      keyboard / cut end).
"""

